// Наповнює базу тестовими книгами через REST API: node seed.mjs
const API = process.env.API_URL || "http://localhost:3000/api/books";
const books = [
  ["Кобзар", "Тарас Шевченко", "А-БА-БА-ГА-ЛА-МА-ГА", "Поезія", 350, 12],
  ["1984", "Джордж Орвелл", "Фабула", "Антиутопія", 420, 8],
  ["Маленький принц", "Антуан де Сент-Екзюпері", "Видавництво Старого Лева", "Казка", 280, 15],
  ["Гаррі Поттер і філософський камінь", "Дж. К. Ролінґ", "А-БА-БА-ГА-ЛА-МА-ГА", "Фентезі", 450, 6],
  ["Тіні забутих предків", "Михайло Коцюбинський", "Ранок", "Класика", 190, 10],
  ["451° за Фаренгейтом", "Рей Бредбері", "КСД", "Фантастика", 380, 5],
  ["Лісова пісня", "Леся Українка", "Основа", "Класика", 220, 9],
  ["Вбивство в «Східному експресі»", "Агата Крісті", "КСД", "Детектив", 340, 0],
];
for (const [title, author, publisher, genre, price, stock] of books) {
  const res = await fetch(API, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ title, author, publisher, genre, price, stock, description: `${title} — ${author}.` }),
  });
  console.log(res.status, title);
}
